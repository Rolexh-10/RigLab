/* Generates db/seed.sql from the typed catalog (src/data) so the database and the app can never drift.
 *   node --import tsx scripts/gen-seed.ts > db/seed.sql
 * Everything seeded here is SAMPLE data: offers get source 'sample' and only sample stores exist. */
import { PARTS, STORES } from '../src/data';
import { offersFor } from '../src/core';

const q = (v: string | null | undefined): string => (v == null ? 'null' : "'" + v.replace(/'/g, "''") + "'");
const out: string[] = ['-- GENERATED by scripts/gen-seed.ts. SAMPLE data only. Do not edit by hand.', 'begin;'];

for (const p of PARTS) {
  const { id, cat, brand, name, nameAr, generic, price: _price, priceSource: _ps, ...specs } = p as unknown as Record<string, unknown> & { id: string; cat: string; brand?: string; name: string; nameAr?: string; generic?: boolean };
  out.push(`insert into parts (id, cat, brand, name, name_ar, generic, specs) values (${q(id)}, ${q(cat)}, ${q(brand)}, ${q(name)}, ${q(nameAr)}, ${generic ? 'true' : 'false'}, ${q(JSON.stringify(specs))}::jsonb);`);
}
for (const s of STORES) {
  out.push(`insert into stores (id, name_ar, name_en, is_live, url, warranty_ar, warranty_en, delivery_iqd, sponsored) values (${q(s.id)}, ${q(s.nameAr)}, ${q(s.nameEn)}, ${s.live}, ${q(s.url)}, ${q(s.warranty.ar)}, ${q(s.warranty.en)}, ${s.deliveryIQD == null ? 'null' : s.deliveryIQD}, ${s.sponsored});`);
}
for (const p of PARTS) {
  for (const o of offersFor(p.id)) {
    out.push(`insert into offers (part_id, store_id, price_iqd, available, source) values (${q(o.partId)}, ${q(o.storeId)}, ${o.price}, ${o.available}, 'sample');`);
  }
}
out.push('commit;');
process.stdout.write(out.join('\n') + '\n');
